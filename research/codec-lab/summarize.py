"""Validate the recorded experiment and regenerate its Markdown tables."""
from collections import defaultdict
import hashlib
import json
from pathlib import Path
from statistics import median

HERE = Path(__file__).resolve().parent
report = json.loads((HERE / 'results.json').read_text(encoding='utf-8'))
assert report['completed'] and all(row['sha256_verified'] for row in report['results'])
assert hashlib.sha256((HERE / 'codec.rs').read_bytes()).hexdigest() == report['codec_source_sha256']
groups = defaultdict(list)
for row in report['results']:
    groups[row['dataset'], row['method']].append(row)
methods = list(dict.fromkeys(row['method'] for row in report['results']))
assert len(groups) == len(report['datasets']) * len(methods)
for rows in groups.values():
    assert sorted(row['repeat'] for row in rows) == list(range(report['repeats']))
    assert len({row['output_bytes'] for row in rows}) == 1


def size(dataset, method):
    return groups[dataset, method][0]['output_bytes']


def timing(dataset, method, field):
    return median(row[field] for row in groups[dataset, method])


def codec_timing(rows, operation):
    values = [row[operation].get('codec_ms') for row in rows]
    return f'{median(values):.2f}' if all(v is not None for v in values) else 'n/a'


lines = [
    '# Codec experiment measurements', '',
    'Generated by `python research/codec-lab/summarize.py` from [results.json](results.json).', '',
    f"All **{len(report['results'])} creation/extraction pairs** recovered the original canonical TAR SHA-256. "
    'The isolated Rust test suite also passed its three tests covering inverse transforms, framing, '
    'round trips, truncation, corruption, and length limits. This is not a production security validation.', '',
    '## Scope and timing', '',
    '* Machine: Intel Core Ultra 9 185H, Windows 11; CPU model checked from the local Windows hardware registry. '
    'All new measurements are CPU-only. No new GPU or peak-memory measurement was performed.',
    '* Three repetitions per method and dataset, with rotated method order. Tables show medians. '
    'Filesystem cache was warm/uncontrolled; power state, core placement, and background load were not controlled. '
    'Small differences are not evidence of a reliable speedup.',
    '* Each method receives the same deterministic TAR bytes. File content is capped at 16 MiB per dataset, '
    'plus TAR metadata and padding. Canterbury is used in full. These are prefixes, not the complete larger corpora.',
    '* Creation and recovery times include process startup, input reads, compression/decompression, output writes, '
    'and process exit. The research executable and Python worker explicitly flush and sync output. '
    'The external RAR tool controls its own durability behavior.',
    '* Codec-only times exclude process startup, input/output file I/O, and Rayon-pool construction. '
    'The Rust encoding timer includes sampling and the original-data checksum; its decoder includes checksum validation. '
    'The LZMA2 timer wraps the liblzma call. RAR does not expose this timing in the harness.',
    '* Recovery means decoding the canonical TAR payload, not extracting its member files. '
    'Directory traversal, TAR creation/member extraction, encryption, IDP sign-in, and the desktop interface are outside the timed region.',
    '* `adaptive` is this research selector, **not production Auto**. `-1` and `-8` denote one or eight configured workers; '
    'they do not imply that every stage uses that many cores. Zstandard decoding here is a single stream.',
    '* Zstandard levels 1, 3, and 9 use the same research wrapper and raw fallback. '
    'LZMA2 is Python/liblzma preset 6, 32 MiB dictionary, one worker, XZ/CRC64 framing; '
    'this is not a benchmark of the 7-Zip application. RAR uses methods 3 and 5, 32 MiB dictionary, '
    'eight requested threads, and a solid RAR5 archive containing one TAR member.',
    '* Container overhead and backend memory budgets differ. Python process startup affects LZMA2 wall times. '
    'These are specified practical settings, not equal-memory or exhaustive best-setting comparisons.', '',
    '## Main finding: numeric specialization', '',
    'The selector chose stride-16 prediction and bit packing for `raw-sensors`. '
    'It chose the Zstandard-level-3 fallback for all eight other datasets. '
    'This dataset is synthetic, interleaved 16-bit sensor-like data with small residuals; '
    'it is particularly favorable to a strided predictor. Real sensor, scientific, and financial data remain untested.', '',
    '| Method | Output bytes | Output / input | Create ms | Recover ms | Encode-only ms | Decode-only ms |',
    '|---|---:|---:|---:|---:|---:|---:|',
]
for method in methods:
    rows = groups['raw-sensors', method]
    lines.append(f"| {method} | {rows[0]['output_bytes']:,} | "
                 f"{100 * rows[0]['output_bytes'] / rows[0]['input_bytes']:.2f}% | "
                 f"{timing('raw-sensors', method, 'create_ms'):.2f} | "
                 f"{timing('raw-sensors', method, 'extract_ms'):.2f} | "
                 f"{codec_timing(rows, 'encode')} | {codec_timing(rows, 'decode')} |")
lines += ['', 'Compared with eight-worker Zstandard level 3, the prototype produces '
          f"**{100 * (1 - size('raw-sensors', 'adaptive-8') / size('raw-sensors', 'zstd3-8')):.1f}% fewer bytes**, "
          f"with **{timing('raw-sensors', 'zstd3-8', 'create_ms') / timing('raw-sensors', 'adaptive-8', 'create_ms'):.2f}x faster creation** "
          f"and **{timing('raw-sensors', 'zstd3-8', 'extract_ms') / timing('raw-sensors', 'adaptive-8', 'extract_ms'):.2f}x faster payload recovery** "
          'on this input. Those speed factors use complete process time, not kernel-only time.', '',
          'The numeric compressed bytes are identical with one and eight workers. '
          'Thus the ratio gain comes from the transform, while chunk parallelism reduces computation time. '
          'Independent 1 MiB chunks are a deliberate history/parallelism tradeoff.', '',
          '## Findings that limit the result', '',
          '* **Text density remains a weakness.** On the enwik8 prefix, the research selector falls back to Zstandard. '
          'The tested LZMA2 and RAR configurations produce smaller files but take longer to create them. '
          'The experiment does not establish a superior general-purpose compressor.',
          '* **History can matter more than worker count.** On similar files, eight-worker Zstandard level 3 produces '
          'substantially more bytes than its single-worker run. An effective future design needs shared history or '
          'appropriate job boundaries, rather than simply splitting every input into more independent work.',
          '* **Higher levels do not win every ratio comparison.** Zstandard level 1 is smaller than level 3 on '
          'the JSON and CSV prefixes. The experimental selector only chooses between the numeric path and level 3; '
          'it does not yet solve general backend/level optimization.',
          '* **Sampling still costs time.** On fallback inputs the output matches the corresponding direct level-3 run exactly, '
          'but sampling adds work. Some measured wall times move in either direction because of noise. '
          'Do not interpret a slightly faster fallback run as an algorithmic improvement.',
          '* **The corpus labels need care.** The `heldout-mixed` prefix includes only `manual.bin`; its random second file '
          'falls outside the 16 MiB budget. The ZIP prefix is a partial byte stream, not a complete independently unpackable ZIP. '
          'These runs cannot establish performance on complete mixed archives or complete ZIP inputs.', '',
          '## All measurements', '',
          'Output ratio is compressed bytes divided by canonical TAR bytes; lower is smaller. '
          'Creation ranges expose run-to-run variation. See the raw JSON for recovery ranges, codec-only times, '
          'commands, hashes, selected methods, and exact source-prefix membership.', '']
for dataset in report['datasets']:
    name = dataset['name']
    lines += [f'### {name}', '', f"Input: {dataset['input_bytes']:,} bytes.", '',
              '| Method | Output bytes | Output / input | Create median ms | Create range ms | Recover median ms |',
              '|---|---:|---:|---:|---:|---:|']
    for method in methods:
        rows = groups[name, method]
        times = [row['create_ms'] for row in rows]
        lines.append(f"| {method} | {size(name, method):,} | "
                     f"{100 * size(name, method) / dataset['input_bytes']:.2f}% | "
                     f"{median(times):.2f} | {min(times):.2f}–{max(times):.2f} | "
                     f"{timing(name, method, 'extract_ms'):.2f} |")
    lines.append('')
lines += ['## Reproducibility', '',
          f"* Research executable SHA-256: `{report['binary_sha256']}`.",
          f"* Numeric codec source SHA-256: `{report['codec_source_sha256']}`.",
          f"* External RAR executable SHA-256: `{report['rar_sha256']}`.",
          '* The harness verifies original corpus hashes, records the selected input prefixes, '
          'and checks exact recovered TAR hashes on every run. The summarizer verifies the source hash, '
          'repetition coverage, deterministic output lengths, and successful recovery flags.',
          '* Read the [design and mathematics](README.md) for implemented versus proposed behavior and reproduction commands.', '']
(HERE / 'measurements.md').write_text('\n'.join(lines), encoding='utf-8')
print(f"Validated {len(report['results'])} round trips; wrote {HERE / 'measurements.md'}")
