"""Verify the existing installed release after an in-place setup/repair.

Does not uninstall or change registry settings. The matching installed-client
identity report must be generated by test-identity-flow.py before this check.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
import tomllib
import winreg

ROOT=Path(__file__).resolve().parents[1]
def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('installer',type=Path)
    p.add_argument('--manifest',type=Path,required=True)
    args=p.parse_args()
    checks=[]
    with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,r'Software\Microsoft\Windows\CurrentVersion\Uninstall\lttl',0,winreg.KEY_READ|winreg.KEY_WOW64_64KEY) as key:
        install=Path(winreg.QueryValueEx(key,'InstallLocation')[0])
        version=winreg.QueryValueEx(key,'DisplayVersion')[0]
        assert version==tomllib.loads((ROOT/'Cargo.toml').read_text())['package']['version']
        assert winreg.QueryValueEx(key,'DisplayIcon')[0]==f'"{install / "lttl-gui.exe"}",0'
    checks.append('Machine registration version, directory and desktop DisplayIcon verified')
    expected=json.loads(args.manifest.read_text())
    nvidia=(install/'gpu/lttl_gpu.dll').exists()
    count=0
    for name,digest in expected.items():
        if name.startswith('gpu/') and not nvidia: continue
        assert sha(install/name)==digest,name
        count+=1
    checks.append(f'All {count} installed payload hashes match release manifest; NVIDIA={nvidia}')
    subprocess.run(['python',str(ROOT/'scripts/test-windows-desktop.py'),str(install),'--installer',str(args.installer)],check=True)
    checks.append('Desktop GUI subsystem, CLI console subsystem and executable/installer icon resources verified')
    def cli(*values):
        return subprocess.check_output([str(install/'lttl.exe'),*map(str,values)],text=True,stderr=subprocess.PIPE,timeout=120)
    assert cli('--version').strip()=='lttl '+version
    checks.append('Installed CLI version and captured terminal output verified')
    with tempfile.TemporaryDirectory(prefix='installed-check-',dir=ROOT/'.qa') as tmp:
        work=Path(tmp); source=work/'sample.txt';source.write_text('lttl release round trip\n'*2000)
        for fmt,backend in [('lttl','auto'),('lttl','lttl-fast'),('lttl','lttl-dense'),('zip','cpu'),('tar-zstd','cpu'),('tar-lz4','cpu')]:
            output=work/(fmt+'-'+backend);dest=work/(fmt+'-'+backend+'-out')
            cli('create',source,'-o',output,'--format',fmt,'--backend',backend)
            cli('test',output);cli('extract',output,'-d',dest)
            assert sha(dest/source.name)==sha(source)
            checks.append(f'Installed {fmt}/{backend} creation, integrity and exact extraction')
    integration=json.loads((ROOT/'docs/audit-retention-validation.json').read_text())
    assert integration['cli_sha256']==sha(install/'lttl.exe')
    assert integration['broker_sha256']==sha(ROOT/'identity-broker/target/release/lttl-key-broker.exe')
    assert integration['checks_passed']==171
    checks.append('Installed client passes 171 mock-IDP audit/retention integration checks; matching client and broker hashes')
    report=dict(scope='Actual Program Files in-place installation/repair; current component selection preserved. Fresh uninstall/other component configuration not repeated for alpha.6.',
        checks_passed=len(checks),checks=checks,installer=args.installer.name,sha256=sha(args.installer),signed=False,
        visual_installer_tested=False,explorer_install_tested=False,installation_directory=str(install),
        desktop_launch_visual='Desktop launcher and title-bar logo observed in prior local alpha.6 build; executable hashes unchanged')
    (ROOT/'docs/windows-installer-validation.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print(f'PASS: {len(checks)} installed release checks')

if __name__=='__main__': main()
